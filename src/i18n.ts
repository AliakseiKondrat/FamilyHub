/** Russian is complete; other languages fall back to it for keys they lack. */
export const DICTS: Record<Lang, Partial<Dict>> = { ru, en, pl, es, it }
export type TKey = keyof Dict

export const LANG_NAMES: Record<Lang, string> = { ru: 'Русский', en: 'English', pl: 'Polski', es: 'Español', it: 'Italiano' }

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  let s: string = DICTS[lang][key] ?? ru[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}

export function useT() {
  const { lang } = useApp()
  return (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars)
}


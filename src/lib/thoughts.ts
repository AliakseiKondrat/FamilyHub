/** The thought for a day: same for both phones, a different one each day. */
export function thoughtFor(date: string, lang: Lang) {
  const list = T[lang] ?? T.en
  const n = Math.floor(Date.UTC(+date.slice(0, 4), +date.slice(5, 7) - 1, +date.slice(8, 10)) / 86400000)
  return list[((n * 7) % list.length + list.length) % list.length]
}
